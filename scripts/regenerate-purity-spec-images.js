// Regenerates every live product image (peptide/amino/kit -- essentials have
// their own photos and no purity line) so its purity line states the purity
// SPECIFICATION ("≥98% PURITY", products.purity_spec), the same wording as the
// vial labels, instead of a test-looking "99% Purity".
//
// Every live image (kits included) was made by generate-dosage-images.js from
// the product's name without its "(...)" annotation and its dosage (or no
// dosage, for the "20mL Vial" amino products). Each image is re-rendered from
// the arguments that reproduce its CURRENT filename exactly; an image whose
// filename can't be reproduced is reported and skipped, never guessed.
//
// New files get a new name (<slug>-spec<N>.webp) rather than overwriting the
// live -tpl files: images are served without Cache-Control, so overwritten
// files could stay stale in browsers, and the old files stay for rollback.
// Writes purity-spec-image-paths.sql (repo root) with the image_path UPDATEs,
// for you to run after the new files are deployed. Nothing is written to the
// database here.
//
// Usage:
//   node regenerate-purity-spec-images.js                 (live catalog, read-only GET)
//   node regenerate-purity-spec-images.js products.json   (same shape, offline)
// purity_spec comes from each product; until that field is live, 98.
const fs = require('fs');
const os = require('os');
const path = require('path');
const { generate, slugify } = require('./generate-dosage-images.js');

const CATALOG_URL = 'https://forgewellpeptide.com/api/products';
const IMAGES = path.join(__dirname, '..', 'images');
const SQL_PATH = path.join(__dirname, '..', 'purity-spec-image-paths.sql');
const DEFAULT_SPEC = 98;
const GENERIC_DOSAGE_VALUES = new Set(['vial', 'pack']);

const strip = (s) => String(s || '').replace(/\s*\([^)]*\)\s*$/, '').trim();
const resolveDosage = (d) => { const s = strip(d); return GENERIC_DOSAGE_VALUES.has(s.toLowerCase()) ? '' : s; };
const specOf = (p) => (p.purity_spec === undefined ? DEFAULT_SPEC : p.purity_spec == null ? null : Number(p.purity_spec));

function moveFile(src, dest) {
  try { fs.renameSync(src, dest); } catch (e) { if (e.code !== 'EXDEV') throw e; fs.copyFileSync(src, dest); fs.unlinkSync(src); }
}

async function loadProducts() {
  if (process.argv[2]) return JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
  const res = await fetch(CATALOG_URL);
  if (!res.ok) throw new Error(`Catalog fetch failed: HTTP ${res.status}`);
  return res.json();
}

async function main() {
  const products = (await loadProducts()).filter((p) => p.category !== 'essential' && p.image_path);
  const byPath = new Map();
  for (const p of products) byPath.set(p.image_path, [...(byPath.get(p.image_path) || []), p]);
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'purity-spec-'));
  const updates = [], skipped = [];
  for (const [oldPath, users] of [...byPath].sort()) {
    const specs = [...new Set(users.map(specOf))];
    if (specs.length > 1) { skipped.push(`${oldPath}: products sharing it have different purity specs (${specs.join(', ')})`); continue; }
    const p = users[0], name = strip(p.name), dosage = resolveDosage(p.dosage);
    const target = path.basename(oldPath, '.png');
    const args = [[name, dosage], [name, '']].find(([n, d]) => `${slugify(n, d)}-tpl` === target);
    if (!args) { skipped.push(`${oldPath}: "${name}" / "${dosage}" doesn't reproduce this filename`); continue; }
    const spec = specs[0];
    const suffix = spec == null ? '-spec-none' : `-spec${String(spec).replace('.', '_')}`;
    const r = await generate({ name: args[0], dosage: args[1], purity: spec == null ? null : String(spec), slugSuffix: suffix, outDir: scratch });
    const newBase = `${slugify(args[0], args[1])}${suffix}`;
    moveFile(r.outPath, path.join(IMAGES, `${newBase}.webp`));
    updates.push({ oldPath, newPath: `images/${newBase}.png`, ids: users.map((u) => u.id), spec, mode: r.mode });
    console.log(`OK   ${oldPath.padEnd(48)} -> images/${newBase}.png  (${users.length} product(s), ${r.mode})`);
  }
  fs.rmSync(scratch, { recursive: true, force: true });

  const q = (s) => `'${s.replace(/'/g, "''")}'`;
  const sql = [
    '-- purity-spec-image-paths.sql -- generated by scripts/regenerate-purity-spec-images.js',
    '-- Points every product at its regenerated image ("≥98% PURITY" -- the purity',
    '-- specification). Run AFTER the frontend with the new images/*-spec*.webp files',
    '-- is deployed. The old -tpl images stay in place (rollback = the reverse UPDATEs).',
    '--',
    '-- Apply INTERACTIVELY (the file leaves the transaction open for review):',
    '--   psql -h localhost -U forgewell -d forgewell_db',
    '--   forgewell_db=> \\i purity-spec-image-paths.sql',
    '--   ...check the NOTICE...',
    '--   forgewell_db=> COMMIT;      -- or ROLLBACK;',
    '',
    'BEGIN;',
    '',
    ...updates.map((u) => `UPDATE products SET image_path = ${q(u.newPath)} WHERE image_path = ${q(u.oldPath)};   -- ${u.ids.join(', ')}`),
    '',
    'DO $$',
    'DECLARE n_new integer; n_old integer;',
    'BEGIN',
    `  SELECT count(*) FILTER (WHERE image_path LIKE 'images/%-spec%'), count(*) FILTER (WHERE image_path IN (${updates.map((u) => q(u.oldPath)).join(', ')}))`,
    '    INTO n_new, n_old FROM products;',
    `  IF n_new <> ${updates.reduce((n, u) => n + u.ids.length, 0)} OR n_old <> 0 THEN`,
    `    RAISE EXCEPTION 'Verification failed: % product(s) on new images (expected ${updates.reduce((n, u) => n + u.ids.length, 0)}), % still on old ones', n_new, n_old;`,
    '  END IF;',
    "  RAISE NOTICE 'OK: % product(s) now use the purity-spec images', n_new;",
    'END',
    '$$;',
    '',
    '-- Now type COMMIT; (or ROLLBACK;)',
    '',
  ].join('\n');
  fs.writeFileSync(SQL_PATH, sql);
  console.log(`\n${updates.length} image(s) regenerated for ${updates.reduce((n, u) => n + u.ids.length, 0)} product(s); ${skipped.length} skipped.`);
  for (const s of skipped) console.log(`SKIP ${s}`);
  console.log(`Wrote ${SQL_PATH} -- nothing was written to the database.`);
}

main().catch((e) => { console.error(e); process.exit(1); });
